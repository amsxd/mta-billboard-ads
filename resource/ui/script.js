function formatRemaining(ad) {
    let rem = 0;
    if (ad.status === 'active') {
        rem = (Number(ad.endAt) || 0) - serverTimestamp;
    } else if (ad.status === 'paused' || ad.status === 'pending') {
        rem = Number(ad.remainingSeconds) || 0;
    }
    if (rem <= 0) return t('status-inactive');
    const h = Math.floor(rem / 3600);
    const m = Math.floor((rem % 3600) / 60);
    return h > 0 ? `${h}h ${m}m` : `${m}m`;
}

function renderAdminList() {
    const listEl = document.getElementById('adminAdsList');
    const search = (document.getElementById('adminSearchInput').value || '').toLowerCase();
    clearElement(listEl);

    const filtered = adminAds.filter(ad => {
        if (adminFilter !== 'all' && ad.status !== adminFilter) return false;
        return `#${ad.id} ${ad.ownerAccount} ${ad.imageUrl}`.toLowerCase().includes(search);
    });

    document.getElementById('adsCounter').textContent = filtered.length;

    if (filtered.length === 0) {
        const empty = document.createElement('div');
        empty.className = 'empty';
        empty.textContent = t('no-ads');
        listEl.appendChild(empty);
        return;
    }

    filtered.forEach(ad => {
        const row = document.createElement('div');
        row.className = 'row' + (selectedAdId === ad.id ? ' selected' : '');
        const idEl = document.createElement('span');
        idEl.className = 'row-id';
        idEl.textContent = '#' + Number(ad.id);
        const nameEl = document.createElement('div');
        nameEl.className = 'row-name';
        nameEl.textContent = `${String(ad.ownerAccount || 'Unknown')} — ${String(ad.imageUrl || '')}`;
        const badge = document.createElement('span');
        const allowedStatuses = ['pending', 'active', 'paused', 'rejected', 'inactive'];
        const status = allowedStatuses.includes(ad.status) ? ad.status : 'inactive';
        badge.className = 'badge status-' + status;
        badge.textContent = t('status-' + status);
        row.append(idEl, nameEl, badge);
        row.onclick = () => {
            selectedAdId = ad.id;
            renderAdminList();
            renderSelectedAdDetails();
        };
        listEl.appendChild(row);
    });
}

