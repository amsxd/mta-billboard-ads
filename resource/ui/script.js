function applyBillboardPosition() {
    if (!selectedBbId) {
        showStatusToast('error', t('bb-select-hint'));
        return;
    }
    const placement = readBillboardPlacement();
    if (!placement) {
        showStatusToast('error', t('bb-position-invalid'));
        return;
    }
    bridge('AdsUI:BillboardAction', 'setposition', selectedBbId, 0,
        placement.x, placement.y, placement.z, placement.rz, placement.interior, placement.dimension);
}

function triggerBillboardAction(action) {
    if (action === 'toggle3d') {
        bridge('AdsUI:BillboardAction', action, 0, 0);
        return;
    }
    if (action === 'getposition') {
        captureBillboardPosition();
        return;
    }
    if (action === 'createhere') {
        bridge('AdsUI:BillboardAction', action, 0, 0);
        return;
    }
    if (action === 'create') {
        const placement = readBillboardPlacement();
        if (!placement) {
            showStatusToast('error', t('bb-position-invalid'));
            return;
        }
        bridge('AdsUI:BillboardAction', action, 0, 0,
            placement.x, placement.y, placement.z, placement.rz, placement.interior, placement.dimension);
        return;
    }
    if (!selectedBbId) {
        showStatusToast('error', t('bb-select-hint'));
        return;
    }
    bridge('AdsUI:BillboardAction', action, selectedBbId, 0);
}

