function loadAdminAdsData(payload) {
    if (!payload) return;
    adminAds = Array.isArray(payload.list) ? payload.list : [];
    if (Array.isArray(payload.billboards)) {
        worldBillboards = payload.billboards;
    }
    if (payload.isAdmin !== undefined) {
        document.getElementById('tabAdmin').classList.toggle('hidden', !payload.isAdmin);
    }
    if (payload.isBuilder !== undefined) {
        document.getElementById('tabBillboards').classList.toggle('hidden', !payload.isBuilder);
    }
    serverTimestamp = Number(payload.serverNow) || Math.floor(Date.now() / 1000);
    renderAdminList();
    renderSelectedAdDetails();
    renderBillboardsList();
    renderSelectedBillboardDetails();
}

