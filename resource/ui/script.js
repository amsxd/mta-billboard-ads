function readBillboardPlacement() {
    const ids = ['bbXInput', 'bbYInput', 'bbZInput', 'bbRotationInput', 'bbInteriorInput', 'bbDimensionInput'];
    const raw = ids.map(id => document.getElementById(id).value.trim());
    if (raw.some(value => value === '')) return null;
    const values = raw.map(Number);
    if (!values.every(Number.isFinite)) return null;
    const [x, y, z, rz, interior, dimension] = values;
    if (x < -3000 || x > 3000 || y < -3000 || y > 3000 || z < -1000 || z > 2000) return null;
    if (rz < 0 || rz > 360 || !Number.isInteger(interior) || interior < 0 || interior > 255) return null;
    if (!Number.isInteger(dimension) || dimension < 0 || dimension > 65535) return null;
    return { x, y, z, rz, interior, dimension };
}

function setBillboardPlacementValues(x, y, z, rz, interior, dimension, notify = true) {
    const values = {
        bbXInput: Number(x),
        bbYInput: Number(y),
        bbZInput: Number(z),
        bbRotationInput: Number(rz),
        bbInteriorInput: Number(interior) || 0,
        bbDimensionInput: Number(dimension) || 0
    };
    for (const [id, value] of Object.entries(values)) {
        document.getElementById(id).value = Number.isFinite(value) ? String(Math.round(value * 100) / 100) : '0';
    }
    if (notify) showStatusToast('success', t('bb-position-loaded'));
}

