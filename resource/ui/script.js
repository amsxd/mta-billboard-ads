function initWindow() {
    const win = document.getElementById('window');
    const bar = document.getElementById('titlebar');

    win.style.left = Math.max(0, Math.round((window.innerWidth - win.offsetWidth) / 2)) + 'px';
    win.style.top = Math.max(0, Math.round((window.innerHeight - win.offsetHeight) / 2)) + 'px';

    let dragging = false, offsetX = 0, offsetY = 0;

    bar.addEventListener('mousedown', e => {
        if (e.target.closest('button')) return;
        dragging = true;
        offsetX = e.clientX - win.offsetLeft;
        offsetY = e.clientY - win.offsetTop;
        e.preventDefault();
    });

    document.addEventListener('mousemove', e => {
        if (!dragging) return;
        win.style.left = Math.max(0, Math.min(e.clientX - offsetX, window.innerWidth - win.offsetWidth)) + 'px';
        win.style.top = Math.max(0, Math.min(e.clientY - offsetY, window.innerHeight - win.offsetHeight)) + 'px';
    });

    document.addEventListener('mouseup', () => { dragging = false; });
}

